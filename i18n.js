function t(source,values={}){
  const translated=locale==='en'?(messages[source]??source):source;
  return translated.replace(/\{(\w+)\}/g,(match,key)=>String(values[key]??match));
}
function translateValue(value,record){
  // Nodes may have changed since the last language switch (viewer, counter,
  // stateful buttons). Re-read their current message instead of restoring stale text.
  const trimmed=value.trim(),source=record?.last===value?record.source:messages[trimmed]?trimmed:null;
  if(!source)return null;
  const translated=value.replace(trimmed,t(source));return {source,last:translated};
}
